'use strict'
// Run with Electron. Uses the real preload, renderer, IPC and tray lifecycle.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const output = path.join(root, 'runs', 'desktop-delivery-smoke-' + Date.now())
fs.mkdirSync(output, { recursive: true })
app.setPath('userData', path.join(output, 'profile'))
process.env.BIOHUB_HOME = path.join(output, 'profile')
process.env.BIOINFORMATICS_HUB_RUNS = path.join(output, 'runs')
process.env.BIOINFORMATICS_HUB_USE_DIST = '1'
process.env.BIOINFORMATICS_HUB_ENGINE = root
require('../apps/bioinformatics-hub-desktop/main.cjs')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
async function until(predicate) { for (let i = 0; i < 150; i++) { if (await predicate()) return; await delay(200) } throw new Error('Desktop smoke condition timed out') }
app.whenReady().then(async () => {
  const checks = []
  try {
    await until(() => BrowserWindow.getAllWindows().length)
    const window = BrowserWindow.getAllWindows()[0]
    const evaluate = source => window.webContents.executeJavaScript(source)
    await until(async () => !window.webContents.isLoading() && await evaluate('Boolean(window.workflowHub && document.querySelector(".wf-start"))'))
    assert.equal(await evaluate('typeof window.require'), 'undefined')
    const catalog = await evaluate('window.workflowHub.catalog()')
    assert.equal(Object.keys(catalog.recipes).length, 28); assert.equal(catalog.templates.length, 3)
    assert.equal(await evaluate('document.querySelectorAll(".wf-launch,input[name=execution-mode]:checked").length'), 0)
    assert.equal(await evaluate('document.querySelectorAll(".wf-header nav button").length'), 5)
    checks.push('start page prepares a draft without selecting or directly launching a workflow')
    window.show(); await delay(800)
    fs.writeFileSync(path.join(output, 'workflow.png'), (await window.webContents.capturePage()).toPNG())
    await evaluate(`document.querySelectorAll('.wf-header nav button')[3].click()`)
    await until(() => evaluate('document.querySelectorAll(".wf-fields input").length === 4'))
    checks.push('settings page renders interpreter, environment and Chrome fields')
    const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/protein-workflow.json'), 'utf8'))
    const session = await evaluate(`window.workflowHub.start(${JSON.stringify(fixture)})`)
    await until(async () => (await evaluate(`window.workflowHub.load(${JSON.stringify(session.id)})`)).status === 'completed')
    const result = await evaluate(`window.workflowHub.load(${JSON.stringify(session.id)})`)
    assert.ok(result.nodes.every(n => n.status === 'succeeded' && n.artifacts.length))
    checks.push('packaged engine executes local preparation and both downstream analyses through IPC')
    await evaluate(`document.querySelectorAll('.wf-header nav button')[2].click()`)
    await until(() => evaluate('Boolean(document.querySelector(".wf-history"))'))
    await evaluate('document.querySelector(".wf-history").click()')
    await until(() => evaluate('document.querySelectorAll(".wf-artifacts li").length > 0'))
    fs.writeFileSync(path.join(output, 'run.png'), (await window.webContents.capturePage()).toPNG())
    assert.equal(await evaluate('[...document.querySelectorAll(".wf-artifacts button")].some(b=>/\\.jsonl?$/.test(b.textContent))'), false)
    checks.push('history opens original files and hides internal JSON')
    await evaluate(`document.querySelectorAll('.wf-header nav button')[1].click()`)
    await until(() => evaluate('document.querySelectorAll(".wf-result-card").length === 3'))
    fs.writeFileSync(path.join(output, 'results.png'), (await window.webContents.capturePage()).toPNG())
    checks.push('result directory lists all original local artifacts without an embedded webpage view')
    window.close(); await delay(300)
    assert.equal(window.isDestroyed(), false); assert.equal(window.isVisible(), false)
    window.show(); assert.equal(window.isVisible(), true)
    checks.push('close hides to tray and window can be reopened')
    fs.writeFileSync(path.join(output, 'validation.json'), JSON.stringify({ok:true,runId:session.id,checks},null,2))
    await require('../apps/bioinformatics-hub-desktop/workflow/client.cjs').call('stop')
    console.log(JSON.stringify({ok:true,checks,output}))
    app.quit()
  } catch (error) {
    fs.writeFileSync(path.join(output, 'validation.json'), JSON.stringify({ok:false,checks,error:error.stack},null,2))
    console.error(error.stack)
    app.exit(1)
  }
})
